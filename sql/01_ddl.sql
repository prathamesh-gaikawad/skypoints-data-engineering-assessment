-- SkyPoints reference schema for Snowflake. Replace SKYPOINTS and stage/file-format
-- names with the deployment's database, storage integration, and retention policy.
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.RAW;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.CORE;
CREATE SCHEMA IF NOT EXISTS SKYPOINTS.MART;

CREATE FILE FORMAT IF NOT EXISTS SKYPOINTS.RAW.CSV_PIPE
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE TRIM_SPACE = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;
CREATE FILE FORMAT IF NOT EXISTS SKYPOINTS.RAW.JSON_LINES TYPE = JSON;

-- Generic raw row supports heterogeneous country feeds without destructive coercion.
CREATE TABLE IF NOT EXISTS SKYPOINTS.RAW.MEMBER_FILE_ROWS (
  BATCH_ID VARCHAR NOT NULL,
  FEED_COUNTRY VARCHAR(3) NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER,
  LOADED_AT TIMESTAMP_TZ NOT NULL,
  FIELD_1 VARCHAR, FIELD_2 VARCHAR, FIELD_3 VARCHAR, FIELD_4 VARCHAR,
  FIELD_5 VARCHAR, FIELD_6 VARCHAR, FIELD_7 VARCHAR, FIELD_8 VARCHAR,
  FIELD_9 VARCHAR, FIELD_10 VARCHAR, FIELD_11 VARCHAR,
  RAW_OBJECT VARIANT
);

CREATE TABLE IF NOT EXISTS SKYPOINTS.RAW.REDEMPTION_EVENTS (
  BATCH_ID VARCHAR NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER,
  LOADED_AT TIMESTAMP_TZ NOT NULL,
  PAYLOAD VARIANT NOT NULL
);

CREATE TABLE IF NOT EXISTS SKYPOINTS.CORE.MEMBER_STAGE (
  BATCH_ID VARCHAR NOT NULL,
  MEMBER_ID VARCHAR(18),                  -- globally unique production member ID
  SOURCE_MEMBER_ID VARCHAR(18) NOT NULL,
  MEMBER_NAME VARCHAR(255) NOT NULL,
  ENROLLMENT_DATE DATE NOT NULL,
  LAST_FLIGHT_DATE DATE,
  TIER_CODE VARCHAR(5),
  AGENT_NAME VARCHAR(255),
  STATE_CODE VARCHAR(5),
  COUNTRY_CODE VARCHAR(5) NOT NULL,
  POST_CODE NUMBER(5,0),
  DATE_OF_BIRTH DATE,
  IS_ACTIVE CHAR(1),
  MEMBER_AGE NUMBER(3,0),
  STALE_MEMBER BOOLEAN,
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL,
  SOURCE_ROW_NUMBER NUMBER NOT NULL,
  VALIDATION_ERRORS ARRAY,
  STAGED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SKYPOINTS.CORE.MEMBER_QUARANTINE (
  BATCH_ID VARCHAR NOT NULL,
  FEED_COUNTRY VARCHAR(3), SOURCE_FILE VARCHAR, SOURCE_ROW_NUMBER NUMBER,
  RAW_OBJECT VARIANT, ERROR_CODES ARRAY, QUARANTINED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- Canonical current record: one row per globally unique member. Snowflake
-- constraints are generally informational; enforce uniqueness with MERGE and audits.
CREATE TABLE IF NOT EXISTS SKYPOINTS.CORE.MEMBER_CURRENT (
  MEMBER_ID VARCHAR(18) NOT NULL,
  SOURCE_MEMBER_ID VARCHAR(18) NOT NULL,
  MEMBER_NAME VARCHAR(255) NOT NULL,
  ENROLLMENT_DATE DATE NOT NULL,
  LAST_FLIGHT_DATE DATE,
  TIER_CODE VARCHAR(5), AGENT_NAME VARCHAR(255), STATE_CODE VARCHAR(5),
  COUNTRY_CODE VARCHAR(5) NOT NULL, POST_CODE NUMBER(5,0), DATE_OF_BIRTH DATE,
  MEMBER_AGE NUMBER(3,0), STALE_MEMBER BOOLEAN, IS_ACTIVE CHAR(1),
  SOURCE_UPDATED_AT TIMESTAMP_TZ NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL,
  UPDATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE VIEW SKYPOINTS.MART.MEMBER_AUS AS
  SELECT * FROM SKYPOINTS.CORE.MEMBER_CURRENT WHERE COUNTRY_CODE IN ('AUS','AU');
CREATE OR REPLACE VIEW SKYPOINTS.MART.MEMBER_IND AS
  SELECT * FROM SKYPOINTS.CORE.MEMBER_CURRENT WHERE COUNTRY_CODE IN ('IND','IN');
CREATE OR REPLACE VIEW SKYPOINTS.MART.MEMBER_USA AS
  SELECT * FROM SKYPOINTS.CORE.MEMBER_CURRENT WHERE COUNTRY_CODE IN ('USA','US');

-- Physical target-table DDL when a downstream contract explicitly requires
-- separate tables. Views remain the preferred logical country boundary.
CREATE TABLE IF NOT EXISTS SKYPOINTS.MART.TABLE_AUSTRALIA LIKE SKYPOINTS.CORE.MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS SKYPOINTS.MART.TABLE_INDIA LIKE SKYPOINTS.CORE.MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS SKYPOINTS.MART.TABLE_USA LIKE SKYPOINTS.CORE.MEMBER_CURRENT;

CREATE TABLE IF NOT EXISTS SKYPOINTS.CORE.REDEMPTION_TRANSACTION (
  MEMBER_ID VARCHAR(18) NOT NULL,
  FEED_DATE DATE NOT NULL,
  TXN_ID VARCHAR NOT NULL,
  TXN_DATE DATE NOT NULL,
  PARTNER VARCHAR,
  MILES_REDEEMED NUMBER(18,0) NOT NULL,
  STATUS VARCHAR,
  BATCH_ID VARCHAR NOT NULL,
  SOURCE_FILE VARCHAR NOT NULL,
  LOADED_AT TIMESTAMP_TZ NOT NULL,
  RAW_PAYLOAD VARIANT
);

CREATE TABLE IF NOT EXISTS SKYPOINTS.RAW.BATCH_AUDIT (
  BATCH_ID VARCHAR NOT NULL, FEED_NAME VARCHAR NOT NULL, SOURCE_FILE VARCHAR NOT NULL,
  STARTED_AT TIMESTAMP_TZ, COMPLETED_AT TIMESTAMP_TZ,
  SOURCE_ROWS NUMBER, ACCEPTED_ROWS NUMBER, REJECTED_ROWS NUMBER,
  STATUS VARCHAR, ERROR_MESSAGE VARCHAR
);

-- 2) Normalize all source layouts into a typed stage. TRY_TO_DATE returns NULL
-- on malformed input; validation below routes such records to quarantine.
INSERT INTO SKYPOINTS.CORE.MEMBER_STAGE (
  BATCH_ID, MEMBER_ID, SOURCE_MEMBER_ID, MEMBER_NAME, ENROLLMENT_DATE,
  LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE_CODE, COUNTRY_CODE,
  POST_CODE, DATE_OF_BIRTH, IS_ACTIVE, MEMBER_AGE, STALE_MEMBER,
  SOURCE_UPDATED_AT, SOURCE_FILE, SOURCE_ROW_NUMBER, VALIDATION_ERRORS
)
WITH parsed AS (
  SELECT r.*,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_1 WHEN 'IND' THEN FIELD_1 WHEN 'USA' THEN FIELD_1 END AS SRC_ID,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_2 WHEN 'IND' THEN FIELD_2 WHEN 'USA' THEN FIELD_2 END AS SRC_NAME,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_3 WHEN 'IND' THEN FIELD_4 WHEN 'USA' THEN FIELD_3 END AS SRC_TIER,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_5 WHEN 'IND' THEN FIELD_5 WHEN 'USA' THEN FIELD_4 END AS SRC_ENROLL,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_6 WHEN 'IND' THEN FIELD_7 WHEN 'USA' THEN FIELD_5 END AS SRC_FLIGHT,
    CASE FEED_COUNTRY WHEN 'AUS' THEN FIELD_4 WHEN 'IND' THEN FIELD_3 END AS SRC_DOB,
    CASE FEED_COUNTRY WHEN 'IND' THEN FIELD_6 END AS SRC_MEMBER_TYPE
  FROM SKYPOINTS.RAW.MEMBER_FILE_ROWS r
  WHERE BATCH_ID = :BATCH_ID
), dates AS (
  SELECT *,
    CASE FEED_COUNTRY WHEN 'AUS' THEN TRY_TO_DATE(NULLIF(SRC_ENROLL,'NULL'),'YYYY-MM-DD')
      WHEN 'IND' THEN TRY_TO_DATE(SRC_ENROLL,'MM/DD/YYYY')
      WHEN 'USA' THEN TRY_TO_DATE(LPAD(SRC_ENROLL,8,'0'),'MMDDYYYY') END AS ENROLL_DT,
    CASE FEED_COUNTRY WHEN 'AUS' THEN TRY_TO_DATE(NULLIF(SRC_FLIGHT,'NULL'),'YYYY-MM-DD')
      WHEN 'IND' THEN TRY_TO_DATE(SRC_FLIGHT,'MM/DD/YYYY')
      WHEN 'USA' THEN TRY_TO_DATE(LPAD(SRC_FLIGHT,8,'0'),'MMDDYYYY') END AS FLIGHT_DT,
    CASE FEED_COUNTRY WHEN 'AUS' THEN TRY_TO_DATE(NULLIF(SRC_DOB,'NULL'),'YYYY-MM-DD')
      WHEN 'IND' THEN TRY_TO_DATE(SRC_DOB,'MM/DD/YYYY') END AS DOB_DT
  FROM parsed
), checked AS (
  SELECT *, ARRAY_CONSTRUCT_COMPACT(
    IFF(NULLIF(TRIM(SRC_ID),'') IS NULL,'MISSING_MEMBER_ID',NULL),
    IFF(NULLIF(TRIM(SRC_NAME),'') IS NULL,'MISSING_MEMBER_NAME',NULL),
    IFF(ENROLL_DT IS NULL,'INVALID_OR_MISSING_ENROLLMENT_DATE',NULL),
    IFF(SRC_FLIGHT IS NOT NULL AND TRIM(SRC_FLIGHT) <> '' AND FLIGHT_DT IS NULL,'INVALID_FLIGHT_DATE',NULL),
    IFF(SRC_DOB IS NOT NULL AND UPPER(TRIM(SRC_DOB)) NOT IN ('','NULL') AND DOB_DT IS NULL,'INVALID_DOB',NULL),
    IFF(LENGTH(SRC_ID)>18,'MEMBER_ID_TOO_LONG',NULL),
    IFF(LENGTH(SRC_NAME)>255,'MEMBER_NAME_TOO_LONG',NULL),
    IFF(NULLIF(TRIM(SRC_TIER),'') IS NOT NULL AND SRC_TIER NOT IN ('GLD','SLV','PLT'),'INVALID_TIER',NULL),
    IFF(FEED_COUNTRY NOT IN ('AUS','IND','USA'),'UNSUPPORTED_COUNTRY',NULL),
    NULL
  ) AS ERRORS
  FROM dates
)
SELECT BATCH_ID,
  /* Production member IDs are global. Country prefix is a local demo fallback. */
  FEED_COUNTRY || ':' || SRC_ID, SRC_ID, TRIM(SRC_NAME), ENROLL_DT, FLIGHT_DT,
  NULLIF(UPPER(TRIM(SRC_TIER)),''), NULL, NULL, FEED_COUNTRY, NULL, DOB_DT,
  NULL, IFF(DOB_DT IS NULL,NULL,DATEDIFF(year,DOB_DT,CURRENT_DATE()) -
    IFF(DATEADD(year,DATEDIFF(year,DOB_DT,CURRENT_DATE()),DOB_DT)>CURRENT_DATE(),1,0)),
  IFF(FLIGHT_DT IS NULL,NULL,DATEDIFF(day,FLIGHT_DT,CURRENT_DATE()) > 90),
  LOADED_AT, SOURCE_FILE, SOURCE_ROW_NUMBER, ERRORS
FROM checked;

-- 3) Quarantine records with any validation failures. Keep raw fields and reasons.
INSERT INTO SKYPOINTS.CORE.MEMBER_QUARANTINE
  (BATCH_ID, FEED_COUNTRY, SOURCE_FILE, SOURCE_ROW_NUMBER, RAW_OBJECT, ERROR_CODES)
SELECT s.BATCH_ID, r.FEED_COUNTRY, s.SOURCE_FILE, s.SOURCE_ROW_NUMBER,
       OBJECT_CONSTRUCT_KEEP_NULL('FIELD_1',r.FIELD_1,'FIELD_2',r.FIELD_2,
         'FIELD_3',r.FIELD_3,'FIELD_4',r.FIELD_4,'FIELD_5',r.FIELD_5,
         'FIELD_6',r.FIELD_6,'FIELD_7',r.FIELD_7,'FIELD_8',r.FIELD_8,
         'FIELD_9',r.FIELD_9,'FIELD_10',r.FIELD_10,'FIELD_11',r.FIELD_11), s.VALIDATION_ERRORS
FROM SKYPOINTS.CORE.MEMBER_STAGE s
JOIN SKYPOINTS.RAW.MEMBER_FILE_ROWS r
  ON r.BATCH_ID=s.BATCH_ID AND r.SOURCE_FILE=s.SOURCE_FILE AND r.SOURCE_ROW_NUMBER=s.SOURCE_ROW_NUMBER
WHERE s.BATCH_ID=:BATCH_ID AND ARRAY_SIZE(s.VALIDATION_ERRORS)>0;

-- 4) Idempotent latest-record-wins merge. A deterministic tie-breaker handles
-- same source timestamp; production should prefer source sequence/version.
MERGE INTO SKYPOINTS.CORE.MEMBER_CURRENT t
USING (
  SELECT * FROM SKYPOINTS.CORE.MEMBER_STAGE
  WHERE BATCH_ID=:BATCH_ID AND ARRAY_SIZE(VALIDATION_ERRORS)=0 AND MEMBER_ID IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY MEMBER_ID ORDER BY SOURCE_UPDATED_AT DESC, STAGED_AT DESC,
      SOURCE_FILE DESC, SOURCE_ROW_NUMBER DESC
  )=1
) s
ON t.MEMBER_ID=s.MEMBER_ID
WHEN MATCHED AND s.SOURCE_UPDATED_AT >= t.SOURCE_UPDATED_AT THEN UPDATE SET
  t.SOURCE_MEMBER_ID=s.SOURCE_MEMBER_ID, t.MEMBER_NAME=s.MEMBER_NAME,
  t.ENROLLMENT_DATE=s.ENROLLMENT_DATE, t.LAST_FLIGHT_DATE=s.LAST_FLIGHT_DATE,
  t.TIER_CODE=s.TIER_CODE, t.AGENT_NAME=s.AGENT_NAME, t.STATE_CODE=s.STATE_CODE,
  t.COUNTRY_CODE=s.COUNTRY_CODE, t.POST_CODE=s.POST_CODE, t.DATE_OF_BIRTH=s.DATE_OF_BIRTH,
  t.MEMBER_AGE=s.MEMBER_AGE, t.STALE_MEMBER=s.STALE_MEMBER, t.IS_ACTIVE=s.IS_ACTIVE,
  t.SOURCE_UPDATED_AT=s.SOURCE_UPDATED_AT, t.SOURCE_FILE=s.SOURCE_FILE, t.BATCH_ID=s.BATCH_ID,
  t.UPDATED_AT=CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  MEMBER_ID,SOURCE_MEMBER_ID,MEMBER_NAME,ENROLLMENT_DATE,LAST_FLIGHT_DATE,TIER_CODE,
  AGENT_NAME,STATE_CODE,COUNTRY_CODE,POST_CODE,DATE_OF_BIRTH,MEMBER_AGE,STALE_MEMBER,
  IS_ACTIVE,SOURCE_UPDATED_AT,SOURCE_FILE,BATCH_ID
) VALUES (
  s.MEMBER_ID,s.SOURCE_MEMBER_ID,s.MEMBER_NAME,s.ENROLLMENT_DATE,s.LAST_FLIGHT_DATE,s.TIER_CODE,
  s.AGENT_NAME,s.STATE_CODE,s.COUNTRY_CODE,s.POST_CODE,s.DATE_OF_BIRTH,s.MEMBER_AGE,s.STALE_MEMBER,
  s.IS_ACTIVE,s.SOURCE_UPDATED_AT,s.SOURCE_FILE,s.BATCH_ID
);


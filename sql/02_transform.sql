-- 5) Flatten each nested redemption into one transaction row. TRY_TO_DATE and
-- type/range predicates belong in validation/quarantine before production MERGE.
INSERT INTO SKYPOINTS.CORE.REDEMPTION_TRANSACTION (
  MEMBER_ID,FEED_DATE,TXN_ID,TXN_DATE,PARTNER,MILES_REDEEMED,STATUS,
  BATCH_ID,SOURCE_FILE,LOADED_AT,RAW_PAYLOAD
)
SELECT r.PAYLOAD:member_id::VARCHAR,
       TRY_TO_DATE(r.PAYLOAD:feed_date::VARCHAR,'YYYYMMDD'),
       f.value:txn_id::VARCHAR,
       TRY_TO_DATE(f.value:txn_date::VARCHAR,'YYYYMMDD'),
       f.value:partner::VARCHAR,
       TRY_TO_NUMBER(f.value:miles_redeemed),
       UPPER(f.value:status::VARCHAR), r.BATCH_ID, r.SOURCE_FILE, r.LOADED_AT, f.value
FROM SKYPOINTS.RAW.REDEMPTION_EVENTS r,
     LATERAL FLATTEN(INPUT => r.PAYLOAD:redemptions) f
WHERE r.BATCH_ID=:BATCH_ID
  AND r.PAYLOAD:member_id IS NOT NULL
  AND TRY_TO_DATE(r.PAYLOAD:feed_date::VARCHAR,'YYYYMMDD') IS NOT NULL
  AND TRY_TO_DATE(f.value:txn_date::VARCHAR,'YYYYMMDD') IS NOT NULL
  AND TRY_TO_NUMBER(f.value:miles_redeemed)>=0;

